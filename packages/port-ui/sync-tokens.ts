// Writes src/mcui_tokens.h — the MoonCellar tokens the port UI needs, as C++ constants — from
// docs/design-tokens.css, the same snapshot the mockups are synced from. With --check it only
// compares and exits 1 when the header is stale.
//
//   bun packages/port-ui/sync-tokens.ts [--check]

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..", "..");
const css = readFileSync(join(root, "docs", "design-tokens.css"), "utf8");
const out = join(import.meta.dir, "src", "mcui_tokens.h");

const declared = new Map<string, string>();
for (const match of css.matchAll(/^\s*--([a-z0-9-]+):\s*([^;]+);/gm)) {
  declared.set(match[1], match[2].trim());
}

type Value = { kind: "color"; rgba: number[] } | { kind: "number"; value: number };

const resolve = (name: string, seen: string[] = []): Value => {
  if (seen.includes(name)) throw new Error(`--${name}: refers to itself`);
  const raw = declared.get(name);
  if (raw === undefined) throw new Error(`--${name} is not in docs/design-tokens.css`);
  return evaluate(raw, [...seen, name]);
};

const evaluate = (raw: string, seen: string[]): Value => {
  const hex = raw.match(/^#([0-9a-f]{6})([0-9a-f]{2})?$/i);
  if (hex) {
    const n = parseInt(hex[1], 16);
    const alpha = hex[2] ? parseInt(hex[2], 16) : 255;
    return { kind: "color", rgba: [n >> 16, (n >> 8) & 255, n & 255, alpha] };
  }
  const variable = raw.match(/^var\(--([a-z0-9-]+)\)$/);
  if (variable) return resolve(variable[1], seen);
  const calc = raw.match(/^calc\(var\(--([a-z0-9-]+)\)\s*\*\s*([0-9.]+)\)$/);
  if (calc) {
    const base = resolve(calc[1], seen);
    if (base.kind !== "number") throw new Error(`${raw}: not a length`);
    return { kind: "number", value: base.value * Number(calc[2]) };
  }
  const unit = raw.match(/^([0-9.]+)(px|ms)$/);
  if (unit) {
    // Lengths stay in CSS pixels; durations become seconds, as ImGui counts time
    const value = Number(unit[1]);
    return { kind: "number", value: unit[2] === "ms" ? value / 1000 : value };
  }
  throw new Error(`${raw}: not a colour, a length or a duration`);
};

// CSS name -> C++ name. Only what the port UI draws with.
const colors = [
  "color-accent",
  "color-bg-primary",
  "color-bg-secondary",
  "color-bg-tertiary",
  "color-bg-hover",
  "color-bg-primary-tint",
  "color-border-primary",
  "color-text-primary",
  "color-text-secondary",
  "color-text-muted",
  "color-gray",
  "color-positive",
  "color-negative",
  "color-attention",
];
const numbers = [
  ...Array.from({ length: 10 }, (_, i) => `radius-x${i + 1}`),
  "radius-control",
  "radius-button",
  "padding-x05",
  ...Array.from({ length: 8 }, (_, i) => `padding-x${i + 1}`),
  "gap-x05",
  ...Array.from({ length: 8 }, (_, i) => `gap-x${i + 1}`),
  "duration-fast",
  "duration-base",
  "duration-slow",
];

const cppName = (css: string) =>
  "k" +
  css
    .replace(/-x05$/, "-x0_5")
    .split("-")
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");

const lines = [
  "// Generated by packages/port-ui/sync-tokens.ts from docs/design-tokens.css. Do not edit:",
  "// change the tokens in apps/web/src/lib/app/styles/vars and run the sync.",
  "#pragma once",
  "",
  "namespace mcui {",
  "namespace tokens {",
  "",
  "// Colours as ImGui packs them (IM_COL32: 0xAABBGGRR)",
];
for (const name of colors) {
  const value = resolve(name);
  if (value.kind !== "color") throw new Error(`--${name}: not a colour`);
  const [r, g, b, a] = value.rgba;
  const packed = ((a << 24) | (b << 16) | (g << 8) | r) >>> 0;
  lines.push(
    `constexpr unsigned ${cppName(name)} = 0x${packed.toString(16).padStart(8, "0").toUpperCase()}u;  // --${name}`
  );
}
lines.push("", "// Lengths in CSS pixels (scale them by the UI scale), durations in seconds");
for (const name of numbers) {
  const value = resolve(name);
  if (value.kind !== "number") throw new Error(`--${name}: not a number`);
  lines.push(`constexpr float ${cppName(name)} = ${Number(value.value.toFixed(4))}f;  // --${name}`);
}
lines.push("", "}  // namespace tokens", "}  // namespace mcui", "");
const header = lines.join("\n").replace(/= (\d+)f;/g, "= $1.0f;");

if (process.argv.includes("--check")) {
  const current = (() => {
    try {
      return readFileSync(out, "utf8");
    } catch {
      return "";
    }
  })();
  if (current !== header) {
    console.error("packages/port-ui/src/mcui_tokens.h is stale: run bun packages/port-ui/sync-tokens.ts");
    process.exit(1);
  }
  console.log("packages/port-ui/src/mcui_tokens.h is up to date");
} else {
  writeFileSync(out, header);
  console.log(`Wrote ${out}`);
}
